#[tokio::main]
async fn main() {
    let port: u16 = std::env::var("PORT")
        .ok()
        .and_then(|p| p.parse().ok())
        .unwrap_or(3467);
    let addr = format!("127.0.0.1:{port}");
    let app = Router::new()
        .route("/", get(|| async { page() }))
        .route("/css/maud-ui.css", get(serve_css))
        .route("/css/fonts/InterVariable.woff2", get(serve_inter))
        .route("/css/replica.css", get(serve_replica_css))
        .nest_service("/img", ServeDir::new("examples/linear-replica/img"));
    let listener = tokio::net::TcpListener::bind(&addr).await.unwrap();
    println!("linear replica running on http://{addr}");
    axum::serve(listener, app).await.unwrap();
}

